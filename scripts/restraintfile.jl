"""
    load_restraint_groups(path) -> (groups, meta)

Read `data/restraints/*.json` without a JSON dependency: the file is generated by
`scripts/fetch_restraints.jl` in a fixed shape, and `--project=test` has no JSON3. Each
group comes back as `(rec_residues, lig_residues, dmin, dmax, cutoff)`.
"""
function load_restraint_groups(path)
    isfile(path) || error("""
        restraint file not found: $path
        generate it first:  julia --project=. scripts/fetch_restraints.jl""")
    txt = read(path, String)
    ints(s) = isempty(strip(s)) ? Int[] : parse.(Int, strip.(split(s, ',')))
    groups = NamedTuple[]
    for m in eachmatch(r"\{\"rec_residues\":\s*\[([^\]]*)\]\s*,\s*\"lig_residues\":\s*\[([^\]]*)\]\s*,\s*\"dmin\":\s*([\d.eE+-]+)\s*,\s*\"dmax\":\s*([\d.eE+-]+)\s*,\s*\"cutoff\":\s*(\d+)\}", txt)
        push!(groups, (rec = ints(m.captures[1]), lig = ints(m.captures[2]),
                       dmin = parse(Float64, m.captures[3]),
                       dmax = parse(Float64, m.captures[4]),
                       cutoff = parse(Int, m.captures[5])))
    end
    isempty(groups) && error("no restraint groups parsed from $path -- " *
                             "regenerate it with scripts/fetch_restraints.jl")
    sha = match(r"\"source_air_sha256\":\s*\"([0-9a-f]+)\"", txt)
    return (groups, (n = length(groups),
                     air_sha = sha === nothing ? "?" : sha.captures[1]))
end

"""
    build_restraint_set(groups, rec, lig, cutoff) -> RestraintSet

Map residue numbers onto atom indices. A residue named in the file but absent
from the structure is a hard error: `restraint` refuses an empty atom set
precisely so that this surfaces here rather than as "the restraints are
unsatisfiable everywhere".
"""
function build_restraint_set(groups, rec::AtomTable{T}, lig::AtomTable{T},
                             cutoff::Int) where {T}
    ridx = Dict{Int,Vector{Int32}}(); lidx = Dict{Int,Vector{Int32}}()
    for i in eachindex(rec.coords)
        push!(get!(ridx, Int(rec.resnum[i]), Int32[]), Int32(i))
    end
    for i in eachindex(lig.coords)
        push!(get!(lidx, Int(lig.resnum[i]), Int32[]), Int32(i))
    end
    gs = RestraintGroup{T}[]
    for (k, g) in enumerate(groups)
        members = Restraint{T}[]
        for r in g.rec, l in g.lig
            haskey(ridx, r) || error("group $k names receptor residue $r, which " *
                                     "the structure does not contain")
            haskey(lidx, l) || error("group $k names ligand residue $l, which " *
                                     "the structure does not contain")
            push!(members, restraint(ridx[r], lidx[l], g.dmin, g.dmax; T = T))
        end
        push!(gs, restraint_group(members; cutoff = g.cutoff))
    end
    return restraint_set(gs; cutoff = cutoff)
end

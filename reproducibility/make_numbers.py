#!/usr/bin/env python3
"""Compute the paper's LaTeX numbers and table rows from the archived measurements.

The final comment block in numbers.tex identifies values reported separately
from device tests, console logs and the technical report.
"""
import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(REPO / "scripts"))
from benchmark_cases import benchmark_cases, completed_cases, recovered

RESULTS = REPO / "bench" / "results"
WP8 = REPO / "results" / "wp8" / "comparison_summary.csv"
OUT = HERE / "numbers.tex"

CAMPAIGN_A = "wp8-batch-graniterapids.json"
CAMPAIGN_B = "wp8-batch-tremont-20260820t105514z.json"
REALDOCK_F32 = "realdock-1ggr-f32-tremont-r5-nvidia-geforce-rtx-4090-gpu.json"
REALDOCK_F64 = "realdock-1ggr-f64-tremont-r5-nvidia-geforce-rtx-4090-gpu.json"

BS = chr(92)

HAND_CARRIED = [
    ("tests on CPU", "5,205", "console output of Pkg.test()"),
    ("tests with the GPU extension", "5,282", "console output of a device deploy"),
    ("correlation vs direct O(N^6)", "5.1e-16", "test_correctness.jl"),
    ("CPU/GPU agreement, Float32", "3e-7", "device suite, paper1_hpc 6.5.1"),
    ("CPU/GPU agreement, Float64", "7e-16", "device suite, paper1_hpc 6.5.1"),
    ("pipeline vs its own floor, CPU", "1.11-1.52x", "paper1_hpc 6.3"),
    ("pipeline vs its own floor, GPU", "1.17-2.50x", "paper1_hpc 6.5.2"),
    ("Fourier-domain accumulation", "1.56-1.97x", "paper1_hpc 6.4 row A1"),
    ("real-input transforms", "1.44-3.29x", "paper1_hpc 6.4 row A2"),
    ("translation scan rewrite", "16.5-60.3x", "paper1_hpc 6.5.5"),
    ("closed-form pose RMSD", "1225x at M=2000", "paper1_hpc 2.6"),
    ("shape-weight crossover", "3.264 / 3.151", "paper1_hpc 6.8"),
    ("fibre pruning", "0 of 200, 1.34x slower", "paper1_hpc 7.1"),
    ("restraints", "78.06% infeasible, 1.26-1.86x", "paper1_hpc 9.1"),
    ("Cn symmetry", "69.4x", "paper1_hpc 9.1"),
    ("noise floor", "9.5-21.5% / 1.4% / 1.6-4.7%", "paper1_hpc 6.1"),
]


def mac(name, value):
    return BS + "newcommand{" + BS + name + "}{" + str(value) + "}"


def thousands(n):
    return "{:,}".format(n).replace(",", "{,}")


def load(name):
    p = RESULTS / name
    if not p.exists():
        sys.exit("missing result file: " + str(p))
    return json.loads(p.read_text(encoding="utf-8"))


def wp8_rows():
    """The external-comparison summary, one dict per case, in file order.

    Read rather than recomputed: `scripts/wp8_summary.py` already derives it from
    the five `comparison.json`, and a second derivation here would be a second
    claim that can drift from the first.
    """
    if not WP8.exists():
        sys.exit("missing " + str(WP8) + " -- run scripts/wp8_summary.py")
    lines = [l for l in WP8.read_text(encoding="utf-8").splitlines()
             if not l.startswith("#")]
    return list(csv.DictReader(lines))


def campaign(doc):
    """Summarise completed enzyme/inhibitor searches and retain all case statuses."""
    cases = benchmark_cases(doc)
    rows = completed_cases(doc)
    n = len(rows)
    per = sorted(r["t_dock_s"] for r in rows)
    floors = sorted(r["search_floor_ca"] for r in rows)
    return dict(
        rows=rows, cases=cases,
        n=n, total=len(cases),
        rank1=recovered(rows, 1),
        hit1k=sum(1 for r in rows if r["hits_in_topk"] > 0),
        clus1=sum(1 for r in rows if r.get("native_cluster_rank") == 1),
        irms4=sum(1 for r in rows
                  if r.get("rank1_irmsd") is not None and r["rank1_irmsd"] <= 4.0),
        t=sum(per), per_lo=per[0], per_hi=per[-1],
        floor_lo=floors[0], floor_hi=floors[-1], floor_med=floors[n // 2],
        angle=rows[0]["search_floor_angle_deg"],
        nrot=doc["nrot"], w1=doc["w1"],
    )


def arms(doc):
    g = next(r for r in doc["rows"] if r.get("arm") == "gpu")
    c = next(r for r in doc["rows"] if r.get("arm") == "cpu")
    return g, c, doc.get("score", {}), doc.get("parity", {})


def main():
    A = campaign(load(CAMPAIGN_A))
    B = campaign(load(CAMPAIGN_B))
    g32, c32, s32, p32 = arms(load(REALDOCK_F32))
    g64, c64, _, _ = arms(load(REALDOCK_F64))

    out = ["% GENERATED by reproducibility/make_numbers.py -- do not edit.",
           "% Sources:"]
    for f in (CAMPAIGN_A, CAMPAIGN_B, REALDOCK_F32, REALDOCK_F64):
        out.append("%   bench/results/" + f)
    out.append("%   results/wp8/comparison_summary.csv")

    out += ["", "% ---- the benchmark campaign, first run ----",
            mac("campCases", A["total"]),
            mac("campOk", A["n"]),
            mac("campRankOne", A["rank1"]),
            mac("campRankOnePct", "{:.1f}".format(100 * A["rank1"] / A["n"])),
            mac("campHitTopK", A["hit1k"]),
            mac("campHitTopKPct", "{:.1f}".format(100 * A["hit1k"] / A["n"])),
            mac("campClusterOne", A["clus1"]),
            mac("campClusterOnePct", "{:.1f}".format(100 * A["clus1"] / A["n"])),
            mac("campIrmsdFour", A["irms4"]),
            mac("campSeconds", "{:.1f}".format(A["t"])),
            mac("campMinutes", "{:.1f}".format(A["t"] / 60)),
            mac("campPerCaseLo", "{:.1f}".format(A["per_lo"])),
            mac("campPerCaseHi", "{:.1f}".format(A["per_hi"])),
            mac("campFloorLo", "{:.2f}".format(A["floor_lo"])),
            mac("campFloorHi", "{:.2f}".format(A["floor_hi"])),
            mac("campFloorMed", "{:.2f}".format(A["floor_med"])),
            mac("campAngleFloor", "{:.2f}".format(A["angle"])),
            mac("campNrot", thousands(A["nrot"])),
            mac("campWone", "{:g}".format(A["w1"]))]

    first = {r["case"]: r for r in A["rows"]}
    second = {r["case"]: r for r in B["rows"]}
    if first.keys() != second.keys():
        raise ValueError("Campaigns have different completed benchmark cases")
    fields = ("native_rank", "hits_in_topk", "native_cluster_rank")
    out += [mac("campHitAll", recovered(A["rows"], A["nrot"])),
            mac("campMaxHitRank", thousands(max(r["native_rank"] for r in A["rows"]))),
            mac("campEqualRanks", sum(all(r[k] == second[c][k] for k in fields)
                                      for c, r in first.items())),
            mac("campEqualEnergy", sum(r["rank1_energy"] == second[c]["rank1_energy"]
                                       for c, r in first.items())),
            mac("dockBestRank", s32["best_rank"])]
    case_lines = []
    for row in A["cases"]:
        if row["status"] == "ok":
            values = [row["native_rank"] or "--", row["hits_in_topk"],
                      row["native_cluster_rank"] or "--", f'{row["t_dock_s"]:.1f}']
        else:
            values = [r"\multicolumn{4}{l}{Atom typing failed}"]
        case_lines.append(" & ".join([row["case"].replace("_", r"\_"), *map(str, values)]) + r" \\")
    out.append(mac("campTableBody", "\n".join(case_lines)))

    out += ["", "% ---- the second campaign, a different machine ----",
            mac("campTwoSeconds", "{:.1f}".format(B["t"])),
            mac("campTwoMinutes", "{:.1f}".format(B["t"] / 60)),
            mac("campTwoRankOne", B["rank1"]),
            mac("campTwoHitTopK", B["hit1k"]),
            mac("campTwoClusterOne", B["clus1"])]

    out += ["", "% ---- the real complex, both arms in one process ----",
            mac("dockGpuFThirtyTwo", "{:.1f}".format(g32["t_dock"])),
            mac("dockGpuFSixtyFour", "{:.1f}".format(g64["t_dock"])),
            mac("dockCpuFThirtyTwo", "{:.1f}".format(c32["extrap_70k_s"])),
            mac("dockSpeedupFThirtyTwo",
                "{:.1f}".format(c32["extrap_70k_s"] / g32["t_dock"])),
            mac("dockSpeedupFSixtyFour",
                "{:.1f}".format(c64["extrap_70k_s"] / g64["t_dock"])),
            mac("dockAtoms", thousands(g32["natoms_rec"] + g32["natoms_lig"])),
            mac("dockNrot", thousands(g32["nrot"])),
            mac("dockRank", s32["native_rank"]),
            mac("dockRmsd", "{:.3f}".format(s32["rank1_rmsd"])),
            mac("dockBest", "{:.5f}".format(s32["best_rmsd"])),
            mac("dockFloor", "{:.5f}".format(s32["search_floor"])),
            mac("dockEnergy", s32["rank1_energy"]),
            mac("parityCompared", thousands(p32["compared"])),
            mac("parityCellAgree", "{:.1f}".format(p32["cell_agree"])),
            mac("parityRelEnergy", "{:.1e}".format(p32["rel_energy"]))]

    # ---- the external comparison (WP8) ----
    W = wp8_rows()
    same = [r for r in W if r["same_rank_band"] == "True"]
    near = [r for r in W if r["pose_within_2A"] == "True"]
    cc = [float(r["top_centre_to_centre"]) for r in same]
    ccall = [float(r["top_centre_to_centre"]) for r in W]
    out += ["", "% ---- the external comparison, five cases ----",
            mac("wpCases", len(W)),
            mac("wpJoint", sum(r["joint_criterion"] == "True" for r in W)),
            mac("wpSameBand", len(same)),
            mac("wpNearN", len(near)),
            mac("wpNearLo", "{:.2f}".format(min(float(r["top_centre_to_our_top1000"]) for r in near))),
            mac("wpNearHi", "{:.2f}".format(max(float(r["top_centre_to_our_top1000"]) for r in near))),
            mac("wpNearSpread", "{:.2f}".format(
                max(float(r["top_centre_to_our_top1000"]) for r in near) -
                min(float(r["top_centre_to_our_top1000"]) for r in near))),
            mac("wpRankLo", min(int(r["top_centre_our_rank_of_that_pose"]) for r in near)),
            mac("wpRankHi", max(int(r["top_centre_our_rank_of_that_pose"]) for r in near)),
            mac("wpCentreLo", "{:.2f}".format(min(cc))),
            mac("wpCentreHi", "{:.2f}".format(max(cc))),
            mac("wpCentreAllLo", "{:.2f}".format(min(ccall))),
            mac("wpCentreAllHi", "{:.2f}".format(max(ccall))),
            mac("wpOddCase", [r["case"] for r in W if r not in near][0]),
            mac("wpOddNear", "{:.2f}".format(
                [float(r["top_centre_to_our_top1000"]) for r in W if r not in near][0]))]
    # Supplementary table of paired ranks and distances.
    body = (" " + BS + BS + " ").join(
        "{} & {} & {} & {:.2f} & {} & {:.2f} & {}".format(
            r["case"], r["their_nn_cluster_rank"] or "--", r["our_nn_cluster_rank"] or "--",
            float(r["top_centre_to_centre"]), r["top_centre_nearest_our_centre_rank"],
            float(r["top_centre_to_our_top1000"]), r["top_centre_our_rank_of_that_pose"])
        for r in W)
    out.append(mac("wpTableBody", body + " " + BS + BS))

    out += ["", "% ---- carried by hand: no committed JSON holds these ----"]
    for label, value, src in HAND_CARRIED:
        out.append("%   {:34} {:30} <- {}".format(label, value, src))

    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")

    nmac = sum(1 for l in out if l.startswith(BS + "newcommand"))
    print("{}: {} macros, {} quantities still carried by hand"
          .format(OUT.name, nmac, len(HAND_CARRIED)))
    for tag, C in (("campaign 1", A), ("campaign 2", B)):
        print("  {}: {}/{} ok, rank1 {}, top-1000 {}, cluster1 {}, {:.1f} min"
              .format(tag, C["n"], C["total"], C["rank1"], C["hit1k"], C["clus1"],
                      C["t"] / 60))
    print("  1GGR f32:   {:.2f} s gpu, {:.1f} s cpu extrapolated, {:.1f}x"
          .format(g32["t_dock"], c32["extrap_70k_s"],
                  c32["extrap_70k_s"] / g32["t_dock"]))
    print("  WP8:        {} cases, same rank band {}, containment {}-{} A on {},"
          " our rank {}-{}"
          .format(len(W), len(same),
                  min(float(r["top_centre_to_our_top1000"]) for r in near),
                  max(float(r["top_centre_to_our_top1000"]) for r in near),
                  len(near),
                  min(int(r["top_centre_our_rank_of_that_pose"]) for r in near),
                  max(int(r["top_centre_our_rank_of_that_pose"]) for r in near)))


if __name__ == "__main__":
    main()

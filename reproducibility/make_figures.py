TAIL = "\n\\end{document}\n"


def load(name):
    return json.loads((RESULTS / name).read_text(encoding="utf-8"))


def write(name, body, sources):
    src = "% GENERATED by reproducibility/make_figures.py -- do not edit.\n"
    src += "".join(f"% data: bench/results/{s}\n" for s in sources)
    BUILD.mkdir(exist_ok=True)
    path = BUILD / f"{name}.tex"
    path.write_text(src + PREAMBLE + body + TAIL, encoding="utf-8", newline="\n")
    return path


def compile_tex(path: Path):
    if not PDFLATEX:
        print(f"  {path.name}: written (no pdflatex on PATH, so no PDF)")
        return
    r = subprocess.run([PDFLATEX, "-interaction=nonstopmode", "-halt-on-error",
                        "-output-directory", str(BUILD), str(path)],
                       capture_output=True, text=True, errors="replace")
    pdf = path.with_suffix(".pdf")
    if r.returncode != 0 or not pdf.exists():
        tail = "\n".join(r.stdout.splitlines()[-25:])
        sys.exit(f"pdflatex failed on {path.name}:\n{tail}\n{r.stderr}")
    if PDFTOCAIRO:
        subprocess.run([PDFTOCAIRO, "-svg", str(pdf), str(path.with_suffix(".svg"))], check=True)
    for ext in (".aux", ".log"):
        path.with_suffix(ext).unlink(missing_ok=True)
    kb = pdf.stat().st_size / 1024
    print(f"  {pdf.name:22} {kb:6.1f} KB" + ("  + svg" if PDFTOCAIRO else ""))


def coords(pairs, fmt="{:g}"):
    return " ".join("(" + fmt.format(x) + "," + fmt.format(y) + ")" for x, y in pairs)


